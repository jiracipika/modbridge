package com.modbridge.pairer;

import org.objectweb.asm.ClassReader;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldNode;
import org.objectweb.asm.tree.MethodNode;

import java.io.IOException;
import java.io.InputStream;
import java.io.PrintStream;
import java.util.ArrayList;
import java.util.Enumeration;
import java.util.List;
import java.util.HashMap;
import java.util.Map;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import java.util.regex.Pattern;

/**
 * Pairs SRG member names (m_123_/f_123_) from Forge's 1.20.1 "-srg" vanilla jar with
 * mojmap names from the official-mapped jar. Members of the same class with the same
 * descriptor are a unique bijection (same vanilla version, only names differ), so
 * descriptor+owner matching is exact — no heuristics.
 * usage: SrgMemberPairer <srg.jar> <mojmap.jar> <out.txt>
 */
public class SrgMemberPairer {

    static final Pattern SRG = Pattern.compile("^[mf]_\\d+_+$");

    public static void main(String[] args) throws Exception {
        Map<String, ClassNode> srg = readClasses(args[0]);
        Map<String, ClassNode> named = readClasses(args[1]);
        PrintStream out = new PrintStream(args[2], "UTF-8");
        out.println("# Generated by SrgMemberPairer: SRG -> mojmap, paired by (class, descriptor)");
        int methods = 0, fields = 0, missing = 0, ambiguous = 0;
        for (Map.Entry<String, ClassNode> e : srg.entrySet()) {
            ClassNode sn = e.getValue();
            ClassNode nn = named.get(e.getKey());
            if (nn == null) { missing++; continue; }
            // key = static flag + descriptor. Desc alone cannot disambiguate distinct
            // same-desc members (legal in JVM, e.g. RandomSource create/createThreadSafe);
            // those groups are counted as ambiguous and left to Linkie-based tooling.
            Map<String, List<String>> namedMethods = new HashMap<>();
            for (MethodNode m : nn.methods) namedMethods.computeIfAbsent(staticKey(m.access) + m.desc, k -> new ArrayList<>()).add(m.name);
            Map<String, List<String>> namedFields = new HashMap<>();
            for (FieldNode f : nn.fields) namedFields.computeIfAbsent(staticKey(f.access) + f.desc, k -> new ArrayList<>()).add(f.name);
            for (MethodNode m : sn.methods) {
                if (SRG.matcher(m.name).matches()) {
                    List<String> cands = namedMethods.get(staticKey(m.access) + m.desc);
                    if (cands != null && cands.size() == 1) { out.println(m.name + "=" + cands.get(0)); methods++; }
                    else if (cands != null) ambiguous++;
                }
            }
            for (FieldNode f : sn.fields) {
                if (SRG.matcher(f.name).matches()) {
                    List<String> cands = namedFields.get(staticKey(f.access) + f.desc);
                    if (cands != null && cands.size() == 1) { out.println(f.name + "=" + cands.get(0)); fields++; }
                    else if (cands != null) ambiguous++;
                }
            }
        }
        out.flush();
        System.out.printf("paired %d methods, %d fields; %d ambiguous (same-desc siblings), %d classes unmatched%n",
                methods, fields, ambiguous, missing);
    }

    static String staticKey(int access) {
        return (access & org.objectweb.asm.Opcodes.ACC_STATIC) != 0 ? "s" : "i";
    }

    static Map<String, ClassNode> readClasses(String jarPath) throws IOException {
        Map<String, ClassNode> out = new HashMap<>();
        try (JarFile jar = new JarFile(jarPath)) {
            for (Enumeration<JarEntry> e = jar.entries(); e.hasMoreElements(); ) {
                JarEntry je = e.nextElement();
                if (!je.getName().endsWith(".class")) continue;
                ClassNode cn = new ClassNode();
                try (InputStream is = jar.getInputStream(je)) {
                    new ClassReader(is).accept(cn, ClassReader.SKIP_CODE | ClassReader.SKIP_FRAMES);
                }
                out.put(cn.name, cn);
            }
        }
        return out;
    }
}
